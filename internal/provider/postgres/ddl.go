package postgres

import (
	"context"
	"fmt"
	"strings"

	"github.com/db-fly/db-fly/internal/domain"
	"github.com/db-fly/db-fly/internal/provider/sqlkit"
)

// ddlDriver 实现 PostgreSQL 方言的结构变更脚本生成。
type ddlDriver struct {
	cfg   domain.ConnectionConfig
	pools *sqlkit.PoolSet
}

func (d *ddlDriver) Name() string { return "PostgreSQL" }

func (d *ddlDriver) Qualified(ref domain.ObjectRef) (string, error) { return qualified(ref) }

func (d *ddlDriver) DatabaseOf(ref domain.ObjectRef) string { return ref.Database }

var pgColumn = sqlkit.ColumnConfig{
	Quoter:              ansi,
	Op:                  "postgresql.script",
	AutoIncrementSuffix: "GENERATED BY DEFAULT AS IDENTITY",
}

func (d *ddlDriver) CreateTable(def domain.TableDefinition) ([]string, error) {
	qualifiedName, err := qualified(def.Ref)
	if err != nil {
		return nil, err
	}
	if len(def.Columns) == 0 {
		return nil, domain.NewError(domain.CodeValidation, "postgresql.script", "建表至少需要定义一个字段")
	}
	lines := make([]string, 0, len(def.Columns)+1)
	primary := make([]string, 0)
	for _, c := range def.Columns {
		line, err := sqlkit.ColumnDefinition(pgColumn, c)
		if err != nil {
			return nil, err
		}
		lines = append(lines, "    "+line)
		if c.PrimaryKey {
			quoted, err := ansi.Ident(c.Name)
			if err != nil {
				return nil, err
			}
			primary = append(primary, quoted)
		}
	}
	if len(primary) > 0 {
		pk, err := ansi.Ident("pk_" + def.Ref.Name)
		if err != nil {
			return nil, err
		}
		lines = append(lines, "    CONSTRAINT "+pk+" PRIMARY KEY ("+strings.Join(primary, ", ")+")")
	}
	stmt := "CREATE TABLE "
	if def.IfNotExists {
		stmt += "IF NOT EXISTS "
	}
	stmt += qualifiedName + " (\n" + strings.Join(lines, ",\n") + "\n)"
	statements := []string{stmt}
	for _, idx := range def.Indexes {
		index, err := sqlkit.CreateIndexStmt(ansi, qualifiedName, idx)
		if err != nil {
			return nil, err
		}
		statements = append(statements, index)
	}
	return statements, nil
}

func (d *ddlDriver) AlterTable(ref domain.ObjectRef, changes []domain.SchemaChange) ([]string, []string, []string, error) {
	if len(changes) == 1 && changes[0].Kind == domain.ChangeRenameTable {
		return d.renameTable(ref, changes[0].NewName)
	}
	qualifiedName, err := qualified(ref)
	if err != nil {
		return nil, nil, nil, err
	}
	var statements, rollbacks, warnings []string
	for _, ch := range changes {
		switch ch.Kind {
		case domain.ChangeAddColumn:
			def, err := sqlkit.ColumnDefinition(pgColumn, ch.Column)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, "ALTER TABLE "+qualifiedName+" ADD COLUMN "+def)
			col, _ := ansi.Ident(ch.Column.Name)
			rollbacks = append(rollbacks, "ALTER TABLE "+qualifiedName+" DROP COLUMN "+col)

		case domain.ChangeModifyColumn:
			col, err := ansi.Ident(ch.Column.Name)
			if err != nil {
				return nil, nil, nil, err
			}
			typ := strings.TrimSpace(ch.Column.Type)
			if typ == "" {
				return nil, nil, nil, domain.NewError(domain.CodeValidation, "postgresql.script",
					"修改字段 %s 需要填写类型", ch.Column.Name)
			}
			if err := sqlkit.ValidateFragment(typ, "字段类型"); err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, "ALTER TABLE "+qualifiedName+" ALTER COLUMN "+col+" TYPE "+typ)
			if ch.Column.Nullable {
				statements = append(statements, "ALTER TABLE "+qualifiedName+" ALTER COLUMN "+col+" DROP NOT NULL")
			} else {
				statements = append(statements, "ALTER TABLE "+qualifiedName+" ALTER COLUMN "+col+" SET NOT NULL")
			}
			if ch.Column.Default != nil {
				value := strings.TrimSpace(*ch.Column.Default)
				if err := sqlkit.ValidateFragment(value, "默认值"); err != nil {
					return nil, nil, nil, err
				}
				statements = append(statements, "ALTER TABLE "+qualifiedName+" ALTER COLUMN "+col+" SET DEFAULT "+value)
			} else {
				statements = append(statements, "ALTER TABLE "+qualifiedName+" ALTER COLUMN "+col+" DROP DEFAULT")
			}
			warnings = append(warnings, fmt.Sprintf("字段 %s 的原定义未纳入回滚脚本，请在执行前备份。", ch.Column.Name))

		case domain.ChangeRenameColumn:
			if strings.TrimSpace(ch.OldName) == "" {
				return nil, nil, nil, domain.NewError(domain.CodeValidation, "postgresql.script", "重命名字段需要填写原字段名")
			}
			old, err := ansi.Ident(ch.OldName)
			if err != nil {
				return nil, nil, nil, err
			}
			next, err := ansi.Ident(ch.Column.Name)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, "ALTER TABLE "+qualifiedName+" RENAME COLUMN "+old+" TO "+next)
			warnings = append(warnings, "重命名字段不会自动更新引用它的视图与函数。")

		case domain.ChangeDropColumn:
			col, err := ansi.Ident(ch.Column.Name)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, "ALTER TABLE "+qualifiedName+" DROP COLUMN "+col)
			warnings = append(warnings, fmt.Sprintf("删除字段 %s 会丢失全部数据，不可自动回滚。", ch.Column.Name))

		case domain.ChangeAddIndex:
			index, err := sqlkit.CreateIndexStmt(ansi, qualifiedName, ch.Index)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, index)
			idx, _ := d.indexName(ref, ch.Index.Name)
			rollbacks = append(rollbacks, "DROP INDEX IF EXISTS "+idx)

		case domain.ChangeDropIndex:
			idx, err := d.indexName(ref, ch.IndexName)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, "DROP INDEX IF EXISTS "+idx)
			warnings = append(warnings, fmt.Sprintf("删除索引 %s 需人工恢复定义。", ch.IndexName))

		case domain.ChangeRenameTable:
			return nil, nil, nil, domain.NewError(domain.CodeValidation, "postgresql.script",
				"重命名表必须单独提交，不能与其他结构变更合并")

		case domain.ChangeTableOptions:
			if ch.Comment != "" {
				statements = append(statements, "COMMENT ON TABLE "+qualifiedName+" IS '"+
					sqlkit.EscapeLiteral(ch.Comment)+"'")
			}
			if ch.Engine != "" || ch.Charset != "" || ch.Collation != "" {
				warnings = append(warnings, "PostgreSQL 不支持表级存储引擎/字符集选项，已忽略。")
			}

		default:
			return nil, nil, nil, domain.NewError(domain.CodeUnsupported, "postgresql.script",
				"PostgreSQL 不支持变更类型 %q", ch.Kind)
		}
	}
	return statements, rollbacks, warnings, nil
}

// renameTable 生成 ALTER TABLE ... RENAME TO 语句与改回原名的回滚脚本。
func (d *ddlDriver) renameTable(ref domain.ObjectRef, newName string) ([]string, []string, []string, error) {
	source, err := qualified(ref)
	if err != nil {
		return nil, nil, nil, err
	}
	newIdent, err := ansi.Ident(newName)
	if err != nil {
		return nil, nil, nil, err
	}
	schema, oldName := splitRef(ref)
	targetRef := domain.ObjectRef{Database: ref.Database, Schema: schema, Name: newName}
	target, err := qualified(targetRef)
	if err != nil {
		return nil, nil, nil, err
	}
	oldIdent, err := ansi.Ident(oldName)
	if err != nil {
		return nil, nil, nil, err
	}
	return []string{"ALTER TABLE " + source + " RENAME TO " + newIdent},
		[]string{"ALTER TABLE " + target + " RENAME TO " + oldIdent},
		[]string{"重命名表不会自动更新引用它的视图、函数与外键约束，请人工复核。"}, nil
}

func (d *ddlDriver) indexName(ref domain.ObjectRef, name string) (string, error) {
	return ansi.Qualified(schemaOf(ref), name)
}

func (d *ddlDriver) DropObject(ref domain.ObjectRef) ([]string, error) {
	qualifiedName, err := qualified(ref)
	if err != nil {
		return nil, err
	}
	return []string{"DROP TABLE IF EXISTS " + qualifiedName + " CASCADE"}, nil
}

// ShowCreate 优先调用服务端 pg_get_tabledef（若扩展提供），否则由元数据反向渲染。
func (d *ddlDriver) ShowCreate(ctx context.Context, ref domain.ObjectRef) (string, error) {
	browser := &metadataBrowser{cfg: d.cfg, pools: d.pools}
	schema, err := browser.Describe(ctx, ref)
	if err != nil {
		return "", err
	}
	owner, table := splitRef(ref)
	if owner == "" {
		owner = "public"
	}
	qualifiedName, err := ansi.Qualified(owner, table)
	if err != nil {
		return "", err
	}
	return sqlkit.RenderCreateTable(ansi, schema, qualifiedName,
		"PostgreSQL 未提供 SHOW CREATE TABLE，以下由 information_schema 元数据反向生成"), nil
}

func (d *ddlDriver) Truncate(qualifiedName string) []string {
	return []string{"TRUNCATE TABLE " + qualifiedName}
}

func (d *ddlDriver) Empty(qualifiedName string) []string {
	return []string{"DELETE FROM " + qualifiedName}
}
