package sqlkit

import (
	"fmt"
	"strings"

	"github.com/db-fly/db-fly/internal/domain"
)

// RenderCreateTable 由元数据反向渲染等价的 CREATE TABLE 脚本。
// 用于没有 SHOW CREATE TABLE 的方言（PostgreSQL / SQL Server / Oracle 回退），
// 或在服务端 DDL 权限不足时提供可复核的建表 SQL。
func RenderCreateTable(q Quoter, schema domain.TableSchema, qualified, header string) string {
	if q.Open == "" || q.Close == "" {
		q = ANSIQuoter
	}
	lines := make([]string, 0, len(schema.Columns)+1)
	primary := make([]string, 0)
	for _, c := range schema.Columns {
		name, err := q.Ident(c.Name)
		if err != nil {
			continue
		}
		typ := strings.TrimSpace(c.RawType)
		if typ == "" {
			typ = strings.TrimSpace(c.DataType)
			if typ != "" && c.Length > 0 && strings.Contains(strings.ToUpper(typ), "CHAR") {
				typ = fmt.Sprintf("%s(%d)", typ, c.Length)
			}
		}
		line := name + " " + typ
		if c.AutoIncrement {
			line += " GENERATED BY DEFAULT AS IDENTITY"
		}
		if c.Nullable {
			line += " NULL"
		} else {
			line += " NOT NULL"
		}
		if c.HasDefault && c.Default != "" {
			line += " DEFAULT " + c.Default
		}
		if c.PrimaryKey {
			primary = append(primary, name)
		}
		lines = append(lines, "    "+line)
	}
	if len(primary) > 0 {
		pk, err := q.Ident("pk_" + schema.Ref.Name)
		if err == nil {
			lines = append(lines, "    CONSTRAINT "+pk+" PRIMARY KEY ("+strings.Join(primary, ", ")+")")
		}
	}
	var b strings.Builder
	if header != "" {
		b.WriteString("-- ")
		b.WriteString(header)
		b.WriteByte('\n')
	}
	b.WriteString("CREATE TABLE ")
	b.WriteString(qualified)
	b.WriteString(" (\n")
	b.WriteString(strings.Join(lines, ",\n"))
	b.WriteString("\n);\n")
	for _, idx := range schema.Indexes {
		if idx.Primary || len(idx.Columns) == 0 {
			continue
		}
		stmt, err := CreateIndexStmt(q, qualified, domain.IndexSpec{
			Name: idx.Name, Columns: idx.Columns, Unique: idx.Unique,
		})
		if err == nil {
			b.WriteString(stmt)
			b.WriteString(";\n")
		}
	}
	return strings.TrimRight(b.String(), "\n")
}
