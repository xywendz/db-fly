package oracle

import (
	"context"
	"database/sql"
	"fmt"
	"strings"

	"github.com/db-fly/db-fly/internal/domain"
	"github.com/db-fly/db-fly/internal/provider/sqlkit"
)

type ddlDriver struct {
	db *sql.DB
}

func (d *ddlDriver) Name() string { return "Oracle" }

// DropIfExists Oracle 不支持 DROP TABLE IF EXISTS。
func (d *ddlDriver) DropIfExists() bool { return false }

func (d *ddlDriver) Qualified(ref domain.ObjectRef) (string, error) { return qualified(ref) }

// DatabaseOf Oracle 只有一个连接池（schema 通过限定名区分），脚本无需切库。
func (d *ddlDriver) DatabaseOf(domain.ObjectRef) string { return "" }

var oraColumn = sqlkit.ColumnConfig{
	Quoter:              ansi,
	Op:                  "oracle.script",
	AutoIncrementSuffix: "GENERATED BY DEFAULT AS IDENTITY",
}

func (d *ddlDriver) CreateTable(def domain.TableDefinition) ([]string, error) {
	qualifiedName, err := qualified(def.Ref)
	if err != nil {
		return nil, err
	}
	if len(def.Columns) == 0 {
		return nil, domain.NewError(domain.CodeValidation, "oracle.script", "建表至少需要定义一个字段")
	}
	lines := make([]string, 0, len(def.Columns)+1)
	primary := make([]string, 0)
	for _, c := range def.Columns {
		line, err := sqlkit.ColumnDefinition(oraColumn, c)
		if err != nil {
			return nil, err
		}
		lines = append(lines, "    "+line)
		if c.PrimaryKey {
			quoted, err := ansi.Ident(c.Name)
			if err != nil {
				return nil, err
			}
			primary = append(primary, quoted)
		}
	}
	if len(primary) > 0 {
		pk, err := ansi.Ident("pk_" + def.Ref.Name)
		if err != nil {
			return nil, err
		}
		lines = append(lines, "    CONSTRAINT "+pk+" PRIMARY KEY ("+strings.Join(primary, ", ")+")")
	}
	statements := []string{
		"CREATE TABLE " + qualifiedName + " (\n" + strings.Join(lines, ",\n") + "\n)",
	}
	for _, idx := range def.Indexes {
		index, err := d.createIndex(def.Ref, idx)
		if err != nil {
			return nil, err
		}
		statements = append(statements, index)
	}
	return statements, nil
}

func (d *ddlDriver) createIndex(ref domain.ObjectRef, idx domain.IndexSpec) (string, error) {
	name, err := d.indexName(ref, idx.Name)
	if err != nil {
		return "", err
	}
	qualifiedName, err := qualified(ref)
	if err != nil {
		return "", err
	}
	columns, err := sqlkit.ColumnNames(ansi, idx.Columns)
	if err != nil {
		return "", err
	}
	kind := "CREATE INDEX"
	if idx.Unique {
		kind = "CREATE UNIQUE INDEX"
	}
	return kind + " " + name + " ON " + qualifiedName + " (" + columns + ")", nil
}

func (d *ddlDriver) indexName(ref domain.ObjectRef, name string) (string, error) {
	quoted, err := ansi.Ident(name)
	if err != nil {
		return "", err
	}
	if owner := ownerOf(ref); owner != "" {
		ownerQuoted, err := ansi.Ident(owner)
		if err != nil {
			return "", err
		}
		return ownerQuoted + "." + quoted, nil
	}
	return quoted, nil
}

func (d *ddlDriver) AlterTable(ref domain.ObjectRef, changes []domain.SchemaChange) ([]string, []string, []string, error) {
	qualifiedName, err := qualified(ref)
	if err != nil {
		return nil, nil, nil, err
	}
	var statements, rollbacks, warnings []string
	for _, ch := range changes {
		switch ch.Kind {
		case domain.ChangeAddColumn:
			def, err := sqlkit.ColumnDefinition(oraColumn, ch.Column)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, "ALTER TABLE "+qualifiedName+" ADD ("+def+")")
			col, _ := ansi.Ident(ch.Column.Name)
			rollbacks = append(rollbacks, "ALTER TABLE "+qualifiedName+" DROP COLUMN "+col)

		case domain.ChangeModifyColumn:
			def, err := sqlkit.ColumnDefinition(oraColumn, ch.Column)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, "ALTER TABLE "+qualifiedName+" MODIFY ("+def+")")
			warnings = append(warnings, fmt.Sprintf("字段 %s 的原定义未纳入回滚脚本，请在执行前备份。", ch.Column.Name))

		case domain.ChangeRenameColumn:
			if strings.TrimSpace(ch.OldName) == "" {
				return nil, nil, nil, domain.NewError(domain.CodeValidation, "oracle.script", "重命名字段需要填写原字段名")
			}
			old, err := ansi.Ident(ch.OldName)
			if err != nil {
				return nil, nil, nil, err
			}
			next, err := ansi.Ident(ch.Column.Name)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, "ALTER TABLE "+qualifiedName+" RENAME COLUMN "+old+" TO "+next)
			warnings = append(warnings, "重命名字段不会自动更新引用它的视图与存储过程。")

		case domain.ChangeDropColumn:
			col, err := ansi.Ident(ch.Column.Name)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, "ALTER TABLE "+qualifiedName+" DROP COLUMN "+col)
			warnings = append(warnings, fmt.Sprintf("删除字段 %s 会丢失全部数据，不可自动回滚。", ch.Column.Name))

		case domain.ChangeAddIndex:
			index, err := d.createIndex(ref, ch.Index)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, index)
			name, _ := d.indexName(ref, ch.Index.Name)
			rollbacks = append(rollbacks, "DROP INDEX "+name)

		case domain.ChangeDropIndex:
			name, err := d.indexName(ref, ch.IndexName)
			if err != nil {
				return nil, nil, nil, err
			}
			statements = append(statements, "DROP INDEX "+name)
			warnings = append(warnings, fmt.Sprintf("删除索引 %s 需人工恢复定义。", ch.IndexName))

		case domain.ChangeTableOptions:
			if ch.Comment != "" {
				statements = append(statements, "COMMENT ON TABLE "+qualifiedName+" IS '"+
					sqlkit.EscapeLiteral(ch.Comment)+"'")
			}
			if ch.Engine != "" || ch.Charset != "" || ch.Collation != "" {
				warnings = append(warnings, "Oracle 不支持表级存储引擎/字符集选项，已忽略。")
			}

		default:
			return nil, nil, nil, domain.NewError(domain.CodeUnsupported, "oracle.script",
				"Oracle 不支持变更类型 %q", ch.Kind)
		}
	}
	return statements, rollbacks, warnings, nil
}

func (d *ddlDriver) DropObject(ref domain.ObjectRef) ([]string, error) {
	qualifiedName, err := qualified(ref)
	if err != nil {
		return nil, err
	}
	return []string{"DROP TABLE " + qualifiedName}, nil
}

// ShowCreate 优先使用 DBMS_METADATA，权限不足时由元数据反向渲染。
func (d *ddlDriver) ShowCreate(ctx context.Context, ref domain.ObjectRef) (string, error) {
	owner := ownerOf(ref)
	if owner == "" {
		if err := d.db.QueryRowContext(ctx, "SELECT USER FROM DUAL").Scan(&owner); err != nil {
			owner = ""
		}
	}
	var raw any
	err := d.db.QueryRowContext(ctx,
		"SELECT DBMS_METADATA.GET_DDL('TABLE', :table, :owner) FROM DUAL",
		namedTable(ref.Name), namedOwner(owner)).Scan(&raw)
	if err == nil {
		if text := strings.TrimSpace(sqlkit.Stringify(raw)); text != "" {
			return strings.TrimSuffix(text, ";"), nil
		}
	}
	browser := &metadataBrowser{db: d.db}
	schema, metaErr := browser.Describe(ctx, ref)
	if metaErr != nil {
		return "", domain.WrapError(domain.CodeQuery, "oracle.script", err,
			"读取建表语句失败（DBMS_METADATA 与元数据回退均不可用）")
	}
	qualifiedName, qerr := qualified(ref)
	if qerr != nil {
		return "", qerr
	}
	return sqlkit.RenderCreateTable(ansi, schema, qualifiedName,
		"DBMS_METADATA 不可用，以下由 all_tab_columns 元数据反向生成"), nil
}

func (d *ddlDriver) Truncate(qualifiedName string) []string {
	return []string{"TRUNCATE TABLE " + qualifiedName}
}

func (d *ddlDriver) Empty(qualifiedName string) []string {
	return []string{"DELETE FROM " + qualifiedName}
}
